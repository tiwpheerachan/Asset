-- โครงฐานข้อมูลฝั่ง PostgreSQL — source of truth เดียวของโครงสร้าง
--
-- ต่างจาก schema.sql เดิม (SQLite) ตรงที่ไม่มีประวัติการย้ายรุ่นปนอยู่:
-- ฐานข้อมูล Postgres เริ่มจากศูนย์แล้วนำเข้าข้อมูลจาก SQLite ครั้งเดียว
-- จึงไม่ต้องมีขั้นอัปเกรดของรุ่นเก่าให้แบกต่อ
--
-- กติกาที่ตั้งใจรักษาไว้ให้เหมือน SQLite เป๊ะ ๆ เพื่อไม่ให้โค้ดแอปต้องเปลี่ยนตาม:
--   · คอลัมน์จริง/เท็จ เก็บเป็น INTEGER 0/1 ไม่ใช่ BOOLEAN — โค้ดเทียบ === 1 อยู่หลายร้อยที่
--   · เวลา เก็บเป็นข้อความ 'YYYY-MM-DD HH:MI:SS' เวลา UTC เหมือนที่ datetime('now')
--     ของ SQLite คืนมา — format.ts เติม "Z" ต่อท้ายแล้วแปลงเป็นเวลาไทยตอนแสดง
--   · id เป็น INTEGER (ไม่ใช่ BIGINT) เพราะโค้ดส่งต่อเป็น number ของ JS

-- แทน datetime('now') ของ SQLite — คืนข้อความเวลา UTC รูปแบบเดียวกัน
CREATE OR REPLACE FUNCTION utc_now_text() RETURNS text
  LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

-- แทน date('now') ของ SQLite — วันที่ตามเวลา UTC
CREATE OR REPLACE FUNCTION utc_today_text() RETURNS text
  LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD') $$;

-- แทน datetime('now', '-15 minutes') — ตัวปรับเวลาของ SQLite เขียนเหมือน interval ของ Postgres
CREATE OR REPLACE FUNCTION utc_now_text(shift text) RETURNS text
  LANGUAGE sql STABLE AS
$$ SELECT to_char((now() AT TIME ZONE 'UTC') + shift::interval, 'YYYY-MM-DD HH24:MI:SS') $$;

-- แทน date('now','localtime') — วันที่ตามเวลาไทย ใช้ตัดสินว่า "วันนี้" คือวันไหนสำหรับคนใช้งาน
CREATE OR REPLACE FUNCTION local_today() RETURNS date
  LANGUAGE sql STABLE AS
$$ SELECT (now() AT TIME ZONE 'Asia/Bangkok')::date $$;

/*
 * ฟังก์ชันอ่านวันเวลาจากข้อความ
 *
 * ระบบเก็บวันเวลาเป็นข้อความหลายรูป: 'YYYY-MM-DD HH:MI:SS' (จากฐานข้อมูล),
 * 'YYYY-MM-DDTHH:MI:SS.sssZ' (จาก JS) และ 'YYYY-MM-DD' (ช่องวันที่ในฟอร์ม)
 * รวมถึงข้อความว่างในคอลัมน์ที่ NOT NULL DEFAULT ''
 *
 * SQLite ปล่อยให้ค่าที่อ่านไม่ออกกลายเป็น NULL เงียบ ๆ — Postgres จะโยน error
 * และทำให้ทั้งคำสั่งล้ม จึงต้องดักไว้ให้ได้พฤติกรรมเดิม ไม่งั้นข้อมูลเก่าแถวเดียว
 * ที่ค่าเพี้ยนจะทำให้หน้าสถิติทั้งหน้าพัง
 */
CREATE OR REPLACE FUNCTION sql_ts(v text) RETURNS timestamp
  LANGUAGE plpgsql IMMUTABLE AS $fn$
BEGIN
  IF v IS NULL OR btrim(v) = '' THEN RETURN NULL; END IF;
  RETURN v::timestamp;
EXCEPTION WHEN others THEN RETURN NULL;
END $fn$;

-- แทน date(x) ของ SQLite — ตัดเวลาออกเหลือแต่วันที่
CREATE OR REPLACE FUNCTION sql_date(v text) RETURNS date
  LANGUAGE plpgsql IMMUTABLE AS $fn$
BEGIN
  IF v IS NULL OR btrim(v) = '' THEN RETURN NULL; END IF;
  RETURN substring(btrim(v) from 1 for 10)::date;
EXCEPTION WHEN others THEN RETURN NULL;
END $fn$;

/*
 * แทน julianday(x) — จำนวนวันแบบทศนิยม
 *
 * โค้ดใช้มันในรูป (julianday(a) - julianday(b)) * 24 เพื่อหาจำนวนชั่วโมง
 * ฟังก์ชันนี้จึงต้องคืนค่าที่ "ผลต่างคูณ 24 ได้ชั่วโมง" ไม่ต้องตรงกับเลข Julian จริง
 */
CREATE OR REPLACE FUNCTION julian(v text) RETURNS double precision
  LANGUAGE sql IMMUTABLE AS
$$ SELECT EXTRACT(EPOCH FROM sql_ts(v)) / 86400.0 $$;

CREATE OR REPLACE FUNCTION julian_now() RETURNS double precision
  LANGUAGE sql STABLE AS
$$ SELECT EXTRACT(EPOCH FROM now()) / 86400.0 $$;

/*
 * แทน CAST(json_extract(data, '$.key') AS INTEGER) ของ SQLite
 *
 * ใช้หาว่าเอกสารใบไหนอ้างถึงใบไหน (ช่องชนิด REQUEST เก็บ id ไว้ใน JSON)
 * SQLite แปลงค่าที่ไม่ใช่ตัวเลขให้เป็น 0 เงียบ ๆ — ที่นี่คืน NULL ซึ่งตรงกว่า
 * เพราะ 0 ไม่มีทางตรงกับ id จริงอยู่แล้ว ผลลัพธ์ของเงื่อนไขจึงเหมือนเดิม
 */
CREATE OR REPLACE FUNCTION json_int(doc text, key text) RETURNS integer
  LANGUAGE plpgsql IMMUTABLE AS $fn$
DECLARE v text;
BEGIN
  v := doc::jsonb ->> key;
  IF v ~ '^-?[0-9]+$' THEN RETURN v::integer; END IF;
  RETURN NULL;
EXCEPTION WHEN others THEN RETURN NULL;
END $fn$;

