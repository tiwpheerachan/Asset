  -- id_token ที่ระบบกลางออกให้ตอนล็อกอิน — ต้องยื่นคืนตอนออกจากระบบ
  -- (ว่าง = ล็อกอินด้วยรหัสผ่านในแอป ไม่ได้ผ่านระบบกลาง)
  id_token   TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT utc_now_text()
);

CREATE TABLE IF NOT EXISTS login_attempts (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT    NOT NULL DEFAULT '',
  ip    TEXT    NOT NULL DEFAULT '',
  ok    INTEGER NOT NULL DEFAULT 0,
  at    TEXT    NOT NULL DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS idx_login_email ON login_attempts(email, at);
CREATE INDEX IF NOT EXISTS idx_login_ip    ON login_attempts(ip, at);

CREATE TABLE IF NOT EXISTS api_keys (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT    NOT NULL,
  -- แปดตัวแรกของกุญแจ ไว้ให้คนดูออกว่าใบไหนเป็นใบไหนโดยไม่ต้องเก็บตัวจริง
  prefix       TEXT    NOT NULL,
  key_hash     TEXT    NOT NULL UNIQUE,
  -- 0 = อ่านอย่างเดียว · 1 = สร้างคำขอได้ด้วย (อนุมัติผ่าน API ไม่ได้ทุกกรณี)
  can_write    INTEGER NOT NULL DEFAULT 0,
  active       INTEGER NOT NULL DEFAULT 1,
  created_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at   TEXT    NOT NULL DEFAULT utc_now_text(),
  last_used_at TEXT,
  calls        INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_apikey_hash ON api_keys(key_hash, active);

CREATE TABLE IF NOT EXISTS webhook_deliveries (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event      TEXT    NOT NULL,
  request_id INTEGER REFERENCES requests(id) ON DELETE SET NULL,
  payload    TEXT    NOT NULL,
  status     TEXT    NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','FAILED','SKIPPED')),
  attempts   INTEGER NOT NULL DEFAULT 0,
  http_code  INTEGER NOT NULL DEFAULT 0,
  error      TEXT    NOT NULL DEFAULT '',
  created_at TEXT    NOT NULL DEFAULT utc_now_text(),
  sent_at    TEXT
);
CREATE INDEX IF NOT EXISTS idx_hook_status ON webhook_deliveries(status, id);

-- "trigger" เป็นคำสงวนของ Postgres จึงต้องใส่อัญประกาศคู่ทุกที่ที่อ้างถึง
CREATE TABLE IF NOT EXISTS backups (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename    TEXT    NOT NULL,
  size        INTEGER NOT NULL DEFAULT 0,
  files_added INTEGER NOT NULL DEFAULT 0,   -- ไฟล์แนบที่คัดลอกเพิ่มในรอบนี้
  ok          INTEGER NOT NULL DEFAULT 0,
  error       TEXT    NOT NULL DEFAULT '',
  "trigger"   TEXT    NOT NULL DEFAULT 'AUTO' CHECK ("trigger" IN ('AUTO','MANUAL','CRON')),
  duration_ms INTEGER NOT NULL DEFAULT 0,
  created_at  TEXT    NOT NULL DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS idx_backups_time ON backups(created_at DESC);

-- สถานะฝั่งบัญชี (OneBook) ที่ยิงกลับเข้ามา
--
-- เก็บเป็นประวัติทีละแถว ไม่ใช่คอลัมน์เดียวบนใบคำขอ เพราะเรื่องหนึ่งเดินหลายจังหวะ
-- (รับเรื่อง → ตั้งเจ้าหนี้ → จ่าย) และเวลามีปัญหาต้องตอบได้ว่าแต่ละจังหวะเกิดเมื่อไหร่
--
-- ดัชนีไม่ซ้ำที่ (request_id, state, external_ref) ทำให้ปลายทางยิงซ้ำได้โดยไม่เกิดแถวซ้ำ
-- ซึ่งจำเป็น เพราะระบบที่ยิง webhook ตามปกติจะลองซ้ำเมื่อไม่แน่ใจว่าถึงหรือยัง
CREATE TABLE IF NOT EXISTS external_status (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id   INTEGER NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  source       TEXT    NOT NULL DEFAULT '',      -- ชื่อกุญแจ API ที่ยิงเข้ามา
  state        TEXT    NOT NULL CHECK (state IN ('RECEIVED','RECORDED','PAID','REJECTED')),
  external_ref TEXT    NOT NULL DEFAULT '',      -- เลขเอกสารฝั่งบัญชี
  external_url TEXT    NOT NULL DEFAULT '',
  amount       DOUBLE PRECISION,
  occurred_at  TEXT    NOT NULL,
  note         TEXT    NOT NULL DEFAULT '',
  created_at   TEXT    NOT NULL DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS idx_extstatus_req ON external_status(request_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_extstatus_once
  ON external_status(request_id, state, external_ref);

-- ตัวเดินเลขเอกสาร แยกตามชุดเลขและเดือน
--
-- เดิมเดินเลขด้วย "หาเลขสูงสุดแล้วบวกหนึ่ง" ซึ่งสองคนที่กดพร้อมกันจะอ่านค่าเดียวกัน
-- แล้วได้เลขซ้ำ ชนข้อจำกัด UNIQUE — การใส่ไว้ใน transaction ไม่ได้ช่วย เพราะระดับ
-- การแยกกันเริ่มต้นของ Postgres ยอมให้สองธุรกรรมอ่านค่าเดิมได้พร้อมกัน
--
-- ตารางนี้ทำให้การเดินเลขเป็นการเขียนแถวเดียว ผู้ที่มาทีหลังจะรอแถวนี้แล้วได้เลขถัดไป
CREATE TABLE IF NOT EXISTS doc_counters (
  scope  TEXT    NOT NULL,        -- ชุดเลข เช่น AP-MPRQ หรือ CN
  period TEXT    NOT NULL,        -- YYYYMM
  seq    INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (scope, period)
);

CREATE TABLE IF NOT EXISTS app_meta (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL DEFAULT ''
);
