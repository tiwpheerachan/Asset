/**
 * ยุบ "อนุมัติเบื้องต้น / อนุมัติจริง" ให้เหลือสายเดียว
 *
 * ที่มา: ระบบเดิมแบ่งการอนุมัติเป็นสองระดับ — เบื้องต้นไว้ขอไฟเขียวก่อนเริ่มเจรจา
 * แล้วค่อยยื่นอนุมัติจริงอีกรอบ แต่ในทางปฏิบัติแทบไม่มีใครใช้สองรอบ กลายเป็นว่า
 * คนตั้งฟอร์มต้องเลือก "ระดับ" ทุกครั้งโดยไม่รู้ว่าต่างกันยังไง แล้วเลือกผิดกันประจำ
 * จนเอกสารค้างอยู่ที่ระดับเบื้องต้นโดยไม่มีใครรู้ว่าต้องกดยื่นอีกที
 *
 * การยุบต้องรักษาลำดับคนอนุมัติไว้ — ขั้นเบื้องต้นเกิด "ก่อน" ขั้นจริงเสมอ
 * เมื่อรวมเป็นสายเดียวจึงต้องอยู่หน้าสาย ไม่ใช่ต่อท้าย
 *
 * และต้องกันขั้นซ้ำ — ฟอร์มที่ตั้งคนคนเดียวกันไว้ทั้งสองระดับ (ซึ่งเป็นวิธีที่คนใช้
 * แทนการเลือกระดับให้ถูก) พอรวมสายแล้วจะกลายเป็นคนเดิมอนุมัติสองครั้งติดกัน
 */

export type StageNode = {
  id: number;
  name: string;
  kind: string;
  stage: string;
  sort_order: number;
  active: number;
};

export type MergePlan = {
  /** ขั้นที่ต้องอัปเดตลำดับใหม่ (ทุกขั้นกลายเป็นสายเดียว) */
  reorder: { id: number; sort_order: number }[];
  /** ขั้นที่ชื่อซ้ำกับขั้นก่อนหน้าในสายเดียวกัน — ปิดใช้ไว้ ไม่ลบทิ้ง */
  deactivate: number[];
};

/**
 * วางแผนการยุบของฟอร์มหนึ่งใบ
 *
 * ปิดใช้แทนการลบ เพราะเป็นการแก้ข้อมูลที่ตั้งค่าไว้ด้วยมือบนระบบจริง —
 * ถ้าเดาผิด คนดูแลกดเปิดกลับได้ในคลิกเดียว แต่ถ้าลบไปแล้วต้องตั้งใหม่ทั้งขั้น
 */
export function mergeStagesPlan(nodes: StageNode[]): MergePlan {
  const ordered = [...nodes].sort((a, b) => {
    // เบื้องต้นมาก่อนจริงเสมอ ภายในระดับเดียวกันเรียงตามลำดับที่ตั้งไว้
    if (a.stage !== b.stage) return a.stage === "PRELIM" ? -1 : 1;
    return a.sort_order - b.sort_order || a.id - b.id;
  });

  const reorder: MergePlan["reorder"] = [];
  const deactivate: number[] = [];
  const seen = new Set<string>();
  let n = 0;

  for (const node of ordered) {
    const key = `${node.kind} ${node.name.trim()}`;
    // ขั้นที่ปิดใช้อยู่แล้วไม่ต้องนับเป็นตัวจับซ้ำ — ไม่งั้นขั้นที่ยังใช้งานอยู่
    // จะโดนปิดตามเพียงเพราะมีชื่อตรงกับขั้นที่เลิกใช้ไปแล้ว
    if (node.active === 1) {
      if (seen.has(key)) deactivate.push(node.id);
      else seen.add(key);
    }
    reorder.push({ id: node.id, sort_order: ++n });
  }

  return { reorder, deactivate };
}
