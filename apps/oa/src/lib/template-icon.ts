export const TEMPLATE_ICON_KEYS = Object.keys(TEMPLATE_ICON_PATHS);

export type TemplateIconKind =
  | { kind: "icon"; key: string }
  | { kind: "image"; file: string }
  | { kind: "emoji"; char: string };

/** อ่านค่าในคอลัมน์ icon ว่าเป็นไอคอนแบบไหน */
export function parseTemplateIcon(icon: string): TemplateIconKind {
  const raw = (icon ?? "").trim();
  if (raw.startsWith("ic:")) {
    const key = raw.slice(3);
    // คีย์ที่ไม่รู้จัก (เช่นลบไอคอนออกจากชุดภายหลัง) ตกกลับไปที่ไอคอนเอกสาร
    return { kind: "icon", key: key in TEMPLATE_ICON_PATHS ? key : "doc" };
  }
  if (raw.startsWith("img:")) {
    const file = raw.slice(4);
    if (file) return { kind: "image", file };
  }
  // ของเดิมเก็บอีโมจิไว้ ต้องแสดงได้เหมือนเดิมโดยไม่ต้องไปไล่แก้ทีละฟอร์ม
  return { kind: "emoji", char: raw || "📄" };
}

export const iconValue = (key: string) => `ic:${key}`;
export const imageValue = (file: string) => `img:${file}`;
