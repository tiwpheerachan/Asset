export function pageByPath(path: string): HelpPage | undefined {
  // ตัด query/hash และจับคู่แบบตรงก่อน แล้วค่อย prefix (เช่น /assets/xxx -> /assets)
  const clean = (path || '/').split('?')[0].split('#')[0];
  const exact = HELP_PAGES.find((p) => p.path === clean);
  if (exact) return exact;
  if (clean.startsWith('/assets/')) return HELP_PAGES.find((p) => p.path === '/assets');
  return undefined;
}
